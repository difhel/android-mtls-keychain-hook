#!/usr/bin/env bash
# Builds module (io.github.difhel.mtlshook) and probe (io.github.difhel.mtlsprobe) APKs without Gradle.
set -euo pipefail
cd "$(dirname "$0")"
# Needs: Android SDK (build-tools + platforms;android-36), JDK 17+, openssl, python3, zip.
SDK=${ANDROID_HOME:-${ANDROID_SDK_ROOT:-$HOME/Library/Android/sdk}}
BT=$(ls -d "$SDK"/build-tools/* | sort -V | tail -1)
AJ=$SDK/platforms/android-36/android.jar
[ -f "$AJ" ] || { echo "missing $AJ: sdkmanager 'platforms;android-36'" >&2; exit 1; }
if [ -n "${JAVA_HOME:-}" ]; then export PATH="$JAVA_HOME/bin:$PATH"; fi
command -v javac >/dev/null || { echo "javac not found: install a JDK 17+" >&2; exit 1; }
KS=${KEYSTORE:-$HOME/.android/debug.keystore}
if [ ! -f "$KS" ]; then
  mkdir -p "$(dirname "$KS")"
  keytool -genkeypair -keystore "$KS" -storepass android -keypass android -alias androiddebugkey \
    -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=Android Debug,O=Android,C=US" >/dev/null
fi
[ -f pki/ca.crt ] || { echo "no pki/ca.crt: run ./gen-pki.sh first" >&2; exit 1; }
OUT=build
rm -rf "$OUT" && mkdir -p "$OUT"

# Xposed API stubs: compile-only, never packaged.
mkdir -p "$OUT/stubs"
javac -nowarn -source 8 -target 8 -bootclasspath "$AJ" -d "$OUT/stubs" $(find xposed-stubs -name '*.java') 2>&1 | grep -v '^warning' || true

python3 - "$OUT" <<'PY'
import subprocess, sys, pathlib
out = pathlib.Path(sys.argv[1])
props = {}
for line in open('module/module.properties'):
    line = line.strip()
    if line and not line.startswith('#'):
        k, v = line.split('=', 1)
        props[k.strip()] = v.strip()
ca = subprocess.run(['openssl', 'x509', '-in', str(pathlib.Path('module') / props['ca.cert']), '-noout',
                     '-subject', '-nameopt', 'RFC2253'], check=True, capture_output=True, text=True).stdout
ca = ca.strip().removeprefix('subject=')
pkgs = [p.strip() for p in props['packages'].split(',') if p.strip()]
hosts = [h.strip().lower() for h in props['hosts'].split(',') if h.strip()]
assert hosts, 'module.properties: hosts must list at least one host'
j = lambda s: '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
gen = out / 'gen/io/github/difhel/mtlshook'
gen.mkdir(parents=True)
(gen / 'Config.java').write_text(f'''package io.github.difhel.mtlshook;
// Generated by build.sh from module/module.properties. Do not edit.
final class Config {{
    static final String KEYCHAIN_ALIAS = {j(props['keychain.alias'])};
    static final String CA_SUBJECT = {j(ca)};
    static final String KEY_TYPE = {j(props['key.type'])};
    static final boolean OFFER_ON_EMPTY_ISSUERS = {str(props['offer.on.empty.issuers'].lower() == 'true').lower()};
    private static final java.util.Set<String> PACKAGES = new java.util.HashSet<>(java.util.Arrays.asList({', '.join(map(j, pkgs))}));
    static boolean isWhitelisted(String pkg) {{ return PACKAGES.contains(pkg); }}
    // Exact host names, or "*.example.com" for any subdomain (not the apex itself).
    private static final String[] HOSTS = {{{', '.join(map(j, hosts))}}};
    static boolean isHostAllowed(String host) {{
        if (host == null || host.isEmpty()) return false;
        String h = host.toLowerCase(java.util.Locale.ROOT);
        if (h.endsWith(".")) h = h.substring(0, h.length() - 1);
        for (String p : HOSTS) {{
            if (p.startsWith("*.") ? h.endsWith(p.substring(1)) && h.length() > p.length() - 1 : h.equals(p)) return true;
        }}
        return false;
    }}
    private Config() {{}}
}}
''')
res = out / 'module-res/values'
res.mkdir(parents=True)
scope = pkgs + ['com.android.keychain']
items = ''.join(f'<item>{p}</item>' for p in scope)
(res / 'arrays.xml').write_text(open('module/res/values/arrays.xml').read().replace('@SCOPE_ITEMS@', items))
(out / 'scope.txt').write_text(' '.join(f'{p}/0' for p in scope) + '\n')
print(f'config: alias={props["keychain.alias"]} ca="{ca}" packages={pkgs} hosts={hosts}')
PY

build_apk() { # name manifest srcdirs resdir assetsdir classpath
  local name=$1 manifest=$2 srcs=$3 resdir=$4 assets=$5 cp=$6 w="$OUT/$1"
  mkdir -p "$w/classes" "$w/dex"
  local link=("$BT/aapt2" link -I "$AJ" --manifest "$manifest" -o "$w/unsigned.apk"
              --min-sdk-version 29 --target-sdk-version 36 --version-code "${VERSION_CODE:-1}" --version-name "0.1")
  if [ -n "$resdir" ]; then "$BT/aapt2" compile --dir "$resdir" -o "$w/res.zip"; link+=("$w/res.zip"); fi
  if [ -n "$assets" ]; then link+=(-A "$assets"); fi
  "${link[@]}"
  javac -nowarn -Xlint:-options -source 8 -target 8 -bootclasspath "$AJ:$BT/core-lambda-stubs.jar" ${cp:+-cp "$cp"} -d "$w/classes" $(find $srcs -name '*.java')
  "$BT/d8" --min-api 29 --lib "$AJ" ${cp:+--classpath "$cp"} --output "$w/dex" $(find "$w/classes" -name '*.class')
  (cd "$w/dex" && zip -q -j ../unsigned.apk classes.dex)
  "$BT/zipalign" -f -p 4 "$w/unsigned.apk" "$w/aligned.apk"
  "$BT/apksigner" sign --ks "$KS" --ks-pass pass:android --key-pass pass:android \
      --ks-key-alias androiddebugkey --out "$OUT/$name.apk" "$w/aligned.apk"
  echo "built $OUT/$name.apk"
}

build_apk mtlshook module/AndroidManifest.xml "module/src $OUT/gen" "$OUT/module-res" module/assets "$OUT/stubs"
build_apk mtlsprobe probe/AndroidManifest.xml probe/src "" "" ""
echo "Vector scope: /data/adb/lspd/cli scope set io.github.difhel.mtlshook $(cat $OUT/scope.txt)"
